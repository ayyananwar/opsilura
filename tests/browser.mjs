import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts',{recursive:true});
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:3000',{waitUntil:'networkidle'});
await page.locator('form[data-ready=true]').waitFor();
await page.getByRole('button',{name:/02 The first step/}).click();
await page.getByText('One problem. One clear plan.').waitFor();
await page.getByRole('button',{name:/03 The progress/}).click();
await page.getByText('A working result. Your call.').waitFor();
await page.getByRole('button',{name:/01 The pile-up/}).click();
await page.getByText('Too many moving parts.').waitFor();
assert.equal(await page.locator('.brand-image').first().getAttribute('src'),'/opsilura-logo.jpeg');
await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
assert.equal(await page.locator('h1').count(),1);
assert.equal(await page.locator('form').count(),1);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.getByRole('button',{name:/02 AI automation/}).click();
await page.getByText('For teams buried in repetitive work.').waitFor({state:'visible'});
await page.getByRole('link',{name:'Discuss ai automation'}).click();
assert.equal(await page.getByLabel('AI automation',{exact:true}).isChecked(),true);
await page.getByLabel('Your name').fill('Alex Example');
await page.getByLabel('Work email').fill('alex@example.com');
await page.getByLabel('Tell us about the work').fill('We need to automate our invoice process.');
const delivery=page.waitForResponse(response=>response.url().endsWith('/api/contact'));
await page.getByRole('button',{name:'Send enquiry'}).click();
const deliveryResponse=await delivery;
assert.equal(deliveryResponse.status(),503,await deliveryResponse.text());
await page.getByText('The form is temporarily unavailable. Please email admin@opsilura.com.').waitFor();
assert.equal(await page.getByLabel('Your name').inputValue(),'Alex Example');
const response=await page.request.post('http://127.0.0.1:3000/api/contact',{headers:{Origin:'http://127.0.0.1:3000'},data:{name:'Alex',email:'bad',message:'short',timeline:'Just exploring'}});
assert.equal(response.status(),400);
const blocked=await page.request.post('http://127.0.0.1:3000/api/contact',{headers:{Origin:'https://untrusted.example'},data:{}});
assert.equal(blocked.status(),403);
await page.goto('http://127.0.0.1:3000/privacy');assert.ok((await page.locator('h1').innerText()).includes('details'));
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:3000',{waitUntil:'networkidle'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.locator('form[data-ready=true]').waitFor();
assert.equal(await page.locator('.service-trigger').first().getAttribute('aria-expanded'),'false');
assert.equal(await page.locator('.mobile-story-flow').isVisible(),true);
assert.equal(await page.evaluate(()=>getComputedStyle(document.querySelector('#email')).fontSize),'16px');
assert.ok((await page.locator('.scene-chapters button').first().boundingBox()).height>=44);
assert.ok((await page.locator('.hero-actions .button').boundingBox()).y<700);
await page.getByRole('button',{name:/01 Custom software/}).click();
await page.getByRole('link',{name:'Discuss custom software'}).click();
assert.equal(await page.getByLabel('Custom software',{exact:true}).isChecked(),true);
await page.goto('http://127.0.0.1:3000',{waitUntil:'networkidle'});
await page.locator('form[data-ready=true]').waitFor();
await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
await page.getByRole('button',{name:'Open menu'}).click();
await page.getByRole('navigation').getByRole('link',{name:'Pricing',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Open menu'}).getAttribute('aria-expanded'),'false');
await page.emulateMedia({reducedMotion:'reduce'});
await page.reload({waitUntil:'networkidle'});
assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).scrollBehavior),'auto');
assert.deepEqual(errors,[]);
console.log('Desktop/mobile layout, navigation, service selection, API validation, preserved form error state, privacy route and reduced motion passed.');
await browser.close();


